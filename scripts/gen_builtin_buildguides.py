"""Generate src/BuiltinBuildGuides.luau from docs/superpowers/guides/*.guide.json.

Each guide is embedded as its (compact) JSON text inside a Luau long-bracket string at a
bracket level guaranteed absent from the text. BuildGuideStore decodes + validates at load.
Do not hand-edit the output. Mirrors gen_builtin_rubrics.py.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = glob.glob(os.path.join(ROOT, "docs", "superpowers", "guides", "*.guide.json"))
OUT = os.path.join(ROOT, "src", "BuiltinBuildGuides.luau")


def bracket_level(text):
    """Smallest level n>=2 whose closing delimiter ]=...=] is absent from text."""
    n = 2
    while ("]" + "=" * n + "]") in text:
        n += 1
    return n


def main():
    payloads = []
    for path in sorted(SRC):
        with open(path, encoding="utf-8") as f:
            obj = json.load(f)  # validates it parses
        compact = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
        payloads.append((os.path.basename(path), compact))

    lines = [
        "--!strict",
        "-- BuiltinBuildGuides: GENERATED by scripts/gen_builtin_buildguides.py from",
        "-- docs/superpowers/guides/*.guide.json. Do NOT hand-edit. Each entry is the raw guide",
        "-- JSON; BuildGuideStore decodes + validates it at load (HttpService:JSONDecode).",
        "",
        "local BuiltinBuildGuides = {}",
        "",
        "BuiltinBuildGuides.list = {",
    ]
    for name, compact in payloads:
        n = bracket_level(compact)
        op, cl = "[" + "=" * n + "[", "]" + "=" * n + "]"
        lines.append(f"\t-- {name}")
        lines.append(f"\t{op}{compact}{cl},")
    lines.append("}")
    lines.append("")
    lines.append("return BuiltinBuildGuides")
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    ok = 0
    for _, compact in payloads:
        json.loads(compact)
        ok += 1
    print(f"generated {OUT} from {len(payloads)} guide(s); round-trip OK: {ok}")


if __name__ == "__main__":
    main()
